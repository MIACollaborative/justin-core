#!/usr/bin/env node

/**
 * Generates a clean API sidebar configuration by reading the typedoc-generated
 * folder structure and skipping intermediate grouping folders (type-aliases, classes, etc.)
 */

const fs = require('fs');
const path = require('path');

const apiDocsPath = path.join(__dirname, '../docs/docs/api');
const outputPath = path.join(__dirname, '../docs/api-sidebar.js');

// Folders to skip when building sidebar
const skipFolders = ['type-aliases', 'classes', 'functions', 'interfaces', 'enums'];

// Module display names
const moduleLabels = {
  'JustInWrapper': 'JustInWrapper',
  'JustInLite': 'JustInLite',
  'handler.type': 'Handler Types',
  'user.type': 'User Types',
  'event.type': 'Event Types',
  'logger.interface': 'Logger',
};

/**
 * Recursively collect doc files from a directory, skipping grouping folders
 */
function collectDocs(dir, basePath = '') {
  const items = [];
  
  if (!fs.existsSync(dir)) return items;
  
  const entries = fs.readdirSync(dir);
  
  entries.forEach(entry => {
    const fullPath = path.join(dir, entry);
    const stat = fs.statSync(fullPath);
    const relativePath = basePath ? `${basePath}/${entry}` : entry;
    
    if (stat.isDirectory()) {
      if (skipFolders.includes(entry)) {
        // Skip the grouping folder but include its contents
        items.push(...collectDocs(fullPath, relativePath));
      } else if (entry !== 'README.md') {
        // Regular directory - recurse
        items.push(...collectDocs(fullPath, relativePath));
      }
    } else if (entry.endsWith('.md') && entry !== 'README.md' && entry !== 'modules.md') {
      // It's a markdown file - add it
      const docId = relativePath.replace(/\.md$/, '');
      const label = path.basename(entry, '.md');
      items.push({ type: 'doc', id: `api/${docId}`, label });
    }
  });
  
  return items;
}

/**
 * Build sidebar structure
 */
function buildSidebar() {
  const categories = [];
  
  const topLevelEntries = fs.readdirSync(apiDocsPath);
  
  topLevelEntries.forEach(entry => {
    const fullPath = path.join(apiDocsPath, entry);
    const stat = fs.statSync(fullPath);
    
    if (!stat.isDirectory() || entry.startsWith('.')) return;
    
    // Check if this is a module folder (has subfolders like handlers/, event/, etc.)
    const subEntries = fs.readdirSync(fullPath);
    const hasModuleSubfolder = subEntries.some(sub => {
      const subPath = path.join(fullPath, sub);
      return fs.statSync(subPath).isDirectory() && !skipFolders.includes(sub);
    });
    
    if (hasModuleSubfolder) {
      // This is a top-level namespace folder (like 'handlers', 'event')
      subEntries.forEach(moduleFolder => {
        const modulePath = path.join(fullPath, moduleFolder);
        if (!fs.statSync(modulePath).isDirectory()) return;
        
        const label = moduleLabels[moduleFolder] || moduleFolder;
        const docs = collectDocs(modulePath, `${entry}/${moduleFolder}`);
        
        if (docs.length > 0) {
          categories.push({
            type: 'category',
            label,
            items: docs
          });
        }
      });
    } else {
      // This is a direct module folder (like 'JustInWrapper')
      const label = moduleLabels[entry] || entry;
      const docs = collectDocs(fullPath, entry);
      
      if (docs.length > 0) {
        categories.push({
          type: 'category',
          label,
          items: docs
        });
      }
    }
  });
  
  return categories;
}

// Generate the sidebar
const sidebarItems = buildSidebar();

// Write to file
const output = `// Auto-generated by scripts/generate-api-sidebar.js
// Run 'node scripts/generate-api-sidebar.js' to regenerate

module.exports = ${JSON.stringify(sidebarItems, null, 2)};
`;

fs.writeFileSync(outputPath, output);
console.log(`✅ Generated API sidebar with ${sidebarItems.length} categories`);
console.log(`   Output: ${outputPath}`);

